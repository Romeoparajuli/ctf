import PDFDocument from "pdfkit";
import ExcelJS from "exceljs";
import {
  AlignmentType,
  Document,
  Footer,
  Header,
  HeadingLevel,
  Packer,
  PageNumber,
  Paragraph,
  Table,
  TableCell,
  TableRow,
  TextRun,
  WidthType,
} from "docx";
import type { ReportColumn, SummaryItem } from "./types.js";
import { formatCellDisplay } from "./format.js";

export interface ExportMeta {
  title: string;
  eventName?: string;
  generatedBy: string;
  generatedAt: string;
  filters: { label: string; value: string }[];
  summary?: SummaryItem[];
}

const ORG_NAME = "Nepal CTF Administration System";

// --- CSV ---
// Friendly headers + formatted values (not raw DB keys/values) so CSV output
// reads the same as the other three formats. A UTF-8 BOM is required for
// Excel on Windows to correctly detect encoding for non-Latin (e.g. Nepali)
// text — without it, Excel misreads the file as the system codepage.
export function buildCsv(rows: Record<string, unknown>[], columns: ReportColumn[]): string {
  const escape = (value: string): string => (/[",\n]/.test(value) ? `"${value.replace(/"/g, '""')}"` : value);
  const lines = [columns.map((c) => escape(c.header)).join(",")];
  for (const row of rows) {
    lines.push(columns.map((c) => escape(formatCellDisplay(row[c.key], c.type))).join(","));
  }
  return "﻿" + lines.join("\n");
}

// --- XLSX ---
export async function buildXlsx(
  rows: Record<string, unknown>[],
  columns: ReportColumn[],
  meta: ExportMeta
): Promise<Buffer> {
  const workbook = new ExcelJS.Workbook();
  workbook.creator = ORG_NAME;
  workbook.created = new Date();

  const sheet = workbook.addWorksheet("Data", { views: [{ state: "frozen", ySplit: 1 }] });
  sheet.columns = columns.map((c) => ({
    header: c.header,
    key: c.key,
    width: c.width ?? 18,
  }));
  sheet.getRow(1).font = { bold: true };
  sheet.getRow(1).fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FFE5E7EB" } };

  for (const row of rows) {
    const values: Record<string, unknown> = {};
    for (const c of columns) {
      const raw = row[c.key];
      if (c.type === "date" && raw) {
        const d = new Date(String(raw));
        values[c.key] = Number.isNaN(d.getTime()) ? raw : d;
      } else if ((c.type === "currency" || c.type === "number") && raw !== null && raw !== undefined) {
        values[c.key] = Number(raw);
      } else {
        values[c.key] = raw ?? "";
      }
    }
    const addedRow = sheet.addRow(values);
    for (const c of columns) {
      const cell = addedRow.getCell(c.key);
      if (c.type === "currency") cell.numFmt = '"NPR" #,##0';
      else if (c.type === "number") cell.numFmt = "#,##0";
      else if (c.type === "date") cell.numFmt = "yyyy-mm-dd hh:mm";
    }
  }

  if (rows.length > 0) {
    sheet.autoFilter = { from: { row: 1, column: 1 }, to: { row: 1, column: columns.length } };
  }

  const summarySheet = workbook.addWorksheet("Summary");
  summarySheet.columns = [
    { header: "Field", key: "field", width: 28 },
    { header: "Value", key: "value", width: 40 },
  ];
  summarySheet.getRow(1).font = { bold: true };
  summarySheet.addRow({ field: "Report", value: meta.title });
  if (meta.eventName) summarySheet.addRow({ field: "Event", value: meta.eventName });
  summarySheet.addRow({ field: "Generated By", value: meta.generatedBy });
  summarySheet.addRow({ field: "Generated At", value: meta.generatedAt });
  for (const f of meta.filters) summarySheet.addRow({ field: `Filter: ${f.label}`, value: f.value });
  if (meta.summary) {
    summarySheet.addRow({});
    for (const s of meta.summary) summarySheet.addRow({ field: s.label, value: s.value });
  }

  const buffer = await workbook.xlsx.writeBuffer();
  return Buffer.from(buffer);
}

// --- PDF ---
// KNOWN LIMITATION: uses pdfkit's standard (Latin-only) fonts. Devanagari/
// Nepali text will not render correctly in PDF output — that requires
// embedding a Unicode font (e.g. Noto Sans Devanagari), which is not bundled
// in this pass. CSV, XLSX and DOCX are unaffected since none of them
// rasterize glyphs at generation time — the reading application supplies the
// font, and all three already carry UTF-8 text correctly.
export function buildPdf(rows: Record<string, unknown>[], columns: ReportColumn[], meta: ExportMeta): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: "A4", margin: 40, bufferPages: true });
    const chunks: Buffer[] = [];
    doc.on("data", (chunk) => chunks.push(chunk));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);

    const pageWidth = doc.page.width - doc.page.margins.left - doc.page.margins.right;

    doc.font("Helvetica-Bold").fontSize(16).text(ORG_NAME.toUpperCase(), { align: "center" });
    doc.moveDown(0.2);
    doc.fontSize(13).text(meta.title.toUpperCase(), { align: "center" });
    doc.moveDown(0.5);
    doc.font("Helvetica").fontSize(9).fillColor("#555555");
    doc.text(`Generated: ${meta.generatedAt}`, { align: "center" });
    if (meta.eventName) doc.text(`Event: ${meta.eventName}`, { align: "center" });
    if (meta.filters.length > 0) {
      doc.text(`Filters: ${meta.filters.map((f) => `${f.label} = ${f.value}`).join(" | ")}`, { align: "center" });
    }
    doc.fillColor("#000000");
    doc.moveDown(0.8);
    doc.moveTo(doc.page.margins.left, doc.y).lineTo(doc.page.width - doc.page.margins.right, doc.y).stroke();
    doc.moveDown(0.6);

    if (meta.summary && meta.summary.length > 0) {
      const left = doc.page.margins.left;
      doc.x = left;
      doc.font("Helvetica-Bold").fontSize(11).text("Summary", left, doc.y);
      doc.moveDown(0.4);
      const perRow = 4;
      const colWidth = pageWidth / perRow;
      const cellHeight = 34;
      const sy = doc.y;
      meta.summary.forEach((s, i) => {
        const col = i % perRow;
        const row = Math.floor(i / perRow);
        const cx = left + col * colWidth;
        const cy = sy + row * cellHeight;
        doc.font("Helvetica-Bold").fontSize(13).text(String(s.value), cx, cy, { width: colWidth - 8 });
        doc.font("Helvetica").fontSize(8).text(s.label, cx, cy + 16, { width: colWidth - 8 });
      });
      const rowCount = Math.ceil(meta.summary.length / perRow);
      doc.x = left;
      doc.y = sy + rowCount * cellHeight + 4;
      doc.moveTo(left, doc.y).lineTo(doc.page.width - doc.page.margins.right, doc.y).stroke();
      doc.moveDown(0.6);
    }

    doc.x = doc.page.margins.left;
    doc.font("Helvetica-Bold").fontSize(11).text("Report Data", doc.x, doc.y);
    doc.moveDown(0.4);

    const widths = proportionalWidths(columns, pageWidth);
    const rowHeight = 18;
    const bottomLimit = doc.page.height - doc.page.margins.bottom;

    function drawHeaderRow() {
      const y = doc.y;
      doc.rect(doc.page.margins.left, y, pageWidth, rowHeight).fill("#E5E7EB");
      doc.fillColor("#000000").font("Helvetica-Bold").fontSize(8);
      let x = doc.page.margins.left;
      columns.forEach((c, i) => {
        doc.text(c.header, x + 3, y + 5, { width: widths[i] - 6, ellipsis: true, lineBreak: false });
        x += widths[i];
      });
      // pdfkit's text() moves doc.x to the end of the text it just drew even
      // when given an explicit x — leaving it there would give the next
      // auto-flow (no-explicit-x) call almost no width to work with,
      // wrapping it character-by-character across many extra pages.
      doc.x = doc.page.margins.left;
      doc.y = y + rowHeight;
      doc.font("Helvetica").fontSize(8);
    }

    drawHeaderRow();

    rows.forEach((row, rowIndex) => {
      if (doc.y + rowHeight > bottomLimit) {
        doc.addPage();
        doc.y = doc.page.margins.top;
        drawHeaderRow();
      }
      const y = doc.y;
      if (rowIndex % 2 === 1) {
        doc.rect(doc.page.margins.left, y, pageWidth, rowHeight).fill("#F9FAFB");
        doc.fillColor("#000000");
      }
      let x = doc.page.margins.left;
      columns.forEach((c, i) => {
        doc.text(formatCellDisplay(row[c.key], c.type), x + 3, y + 5, {
          width: widths[i] - 6,
          ellipsis: true,
          lineBreak: false,
        });
        x += widths[i];
      });
      doc.x = doc.page.margins.left;
      doc.y = y + rowHeight;
    });

    if (rows.length === 0) {
      doc.x = doc.page.margins.left;
      doc.moveDown(0.5);
      doc.font("Helvetica-Oblique").text("No records match the applied filters.", doc.page.margins.left, doc.y, {
        width: pageWidth,
      });
    }

    // Footer + page numbers on every buffered page. Writing inside the
    // bottom margin makes pdfkit think the content overflowed and silently
    // auto-add a fresh page per call unless the bottom margin is zeroed
    // first — the standard workaround for footers with bufferPages.
    const range = doc.bufferedPageRange();
    const savedBottomMargin = doc.page.margins.bottom;
    for (let i = range.start; i < range.start + range.count; i++) {
      doc.switchToPage(i);
      doc.page.margins.bottom = 0;
      const bottom = doc.page.height - savedBottomMargin + 12;
      doc
        .font("Helvetica")
        .fontSize(7)
        .fillColor("#888888")
        .text(`${ORG_NAME} — Generated ${meta.generatedAt}`, doc.page.margins.left, bottom, {
          width: pageWidth / 2,
        });
      doc.text(`Page ${i - range.start + 1} of ${range.count}`, doc.page.margins.left + pageWidth / 2, bottom, {
        width: pageWidth / 2,
        align: "right",
      });
    }

    doc.end();
  });
}

function proportionalWidths(columns: ReportColumn[], totalWidth: number): number[] {
  const weights = columns.map((c) => c.width ?? 15);
  const total = weights.reduce((a, b) => a + b, 0);
  return weights.map((w) => (w / total) * totalWidth);
}

// --- DOCX ---
export async function buildDocx(
  rows: Record<string, unknown>[],
  columns: ReportColumn[],
  meta: ExportMeta
): Promise<Buffer> {
  const headerRow = new TableRow({
    tableHeader: true,
    children: columns.map(
      (c) =>
        new TableCell({
          shading: { fill: "E5E7EB" },
          children: [new Paragraph({ children: [new TextRun({ text: c.header, bold: true })] })],
        })
    ),
  });

  const dataRows = rows.map(
    (row) =>
      new TableRow({
        children: columns.map(
          (c) =>
            new TableCell({
              children: [new Paragraph(formatCellDisplay(row[c.key], c.type))],
            })
        ),
      })
  );

  const dataTable = new Table({
    width: { size: 100, type: WidthType.PERCENTAGE },
    rows: [headerRow, ...dataRows],
  });

  const summaryTable = meta.summary
    ? new Table({
        width: { size: 60, type: WidthType.PERCENTAGE },
        rows: meta.summary.map(
          (s) =>
            new TableRow({
              children: [
                new TableCell({ children: [new Paragraph({ children: [new TextRun({ text: s.label, bold: true })] })] }),
                new TableCell({ children: [new Paragraph(String(s.value))] }),
              ],
            })
        ),
      })
    : null;

  const metaParagraphs = [
    new Paragraph({ text: `Generated: ${meta.generatedAt}`, spacing: { after: 100 } }),
    ...(meta.eventName ? [new Paragraph({ text: `Event: ${meta.eventName}`, spacing: { after: 100 } })] : []),
    new Paragraph({ text: `Generated By: ${meta.generatedBy}`, spacing: { after: 100 } }),
    ...(meta.filters.length > 0
      ? [
          new Paragraph({
            text: `Filters: ${meta.filters.map((f) => `${f.label} = ${f.value}`).join(", ")}`,
            spacing: { after: 200 },
          }),
        ]
      : []),
  ];

  const doc = new Document({
    creator: ORG_NAME,
    title: meta.title,
    sections: [
      {
        headers: {
          default: new Header({
            children: [new Paragraph({ text: ORG_NAME, alignment: AlignmentType.CENTER })],
          }),
        },
        footers: {
          default: new Footer({
            children: [
              new Paragraph({
                alignment: AlignmentType.CENTER,
                children: [
                  new TextRun("Page "),
                  new TextRun({ children: [PageNumber.CURRENT] }),
                  new TextRun(" of "),
                  new TextRun({ children: [PageNumber.TOTAL_PAGES] }),
                ],
              }),
            ],
          }),
        },
        children: [
          new Paragraph({ text: meta.title, heading: HeadingLevel.HEADING_1, alignment: AlignmentType.CENTER }),
          ...metaParagraphs,
          ...(summaryTable
            ? [new Paragraph({ text: "Summary", heading: HeadingLevel.HEADING_2 }), summaryTable, new Paragraph({ text: "" })]
            : []),
          new Paragraph({ text: "Report Data", heading: HeadingLevel.HEADING_2 }),
          rows.length > 0 ? dataTable : new Paragraph("No records match the applied filters."),
        ],
      },
    ],
  });

  return Packer.toBuffer(doc);
}
